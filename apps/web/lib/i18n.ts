const DICTS: Record<Lang, Record<string, string>> = { en, hi, ne };

export function getLang(): Lang {
  if (typeof window === "undefined") return "en";
  const saved = localStorage.getItem("sv-lang") as Lang | null;
  return saved && DICTS[saved] ? saved : "en";
}

export function setLang(l: Lang) {
  localStorage.setItem("sv-lang", l);
  window.dispatchEvent(new CustomEvent("sv-lang-change"));
}

/** React hook: returns t() bound to the current language, re-renders on change. */
export function useI18n() {
  const [lang, setL] = useState<Lang>(getLang());
  useEffect(() => {
    const h = () => setL(getLang());
    window.addEventListener("sv-lang-change", h);
    return () => window.removeEventListener("sv-lang-change", h);
  }, []);
  const t = (k: string): string => DICTS[lang][k] ?? DICTS.en[k] ?? k;
  return { t, lang, setLang };
}
